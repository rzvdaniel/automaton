#!/bin/bash
# Automaton Runner - Local Testing Setup Script
# This script helps testers quickly set up a local Docker runner for testing with Automaton Studio

set -e

# Colors for output
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
BLUE='\033[0;34m'
CYAN='\033[0;36m'
NC='\033[0m' # No Color

# Default values
DEFAULT_RUNNER_NAME="local-test-runner"
DEFAULT_SERVER_URL="https://localhost:7091"

print_header() {
    echo -e "${BLUE}"
    echo "═══════════════════════════════════════════════════════════"
    echo "    Automaton Runner - Local Testing Setup"
    echo "═══════════════════════════════════════════════════════════"
    echo -e "${NC}"
}

print_step() {
    echo -e "${GREEN}[✓]${NC} $1"
}

print_info() {
    echo -e "${CYAN}[ℹ]${NC} $1"
}

print_warning() {
    echo -e "${YELLOW}[⚠]${NC} $1"
}

print_error() {
    echo -e "${RED}[✗]${NC} $1"
}

check_docker() {
    if ! command -v docker &> /dev/null; then
        print_error "Docker is not installed or not in PATH"
        echo ""
        echo "Please install Docker Desktop:"
        echo "  • Windows/Mac: https://www.docker.com/products/docker-desktop"
        echo "  • Linux: https://docs.docker.com/engine/install/"
        exit 1
    fi
    
    if ! docker info &> /dev/null; then
        print_error "Docker daemon is not running"
        echo ""
        echo "Please start Docker Desktop and try again"
        exit 1
    fi
    
    print_step "Docker is installed and running"
}

check_compose() {
    if ! docker compose version &> /dev/null && ! command -v docker-compose &> /dev/null; then
        print_error "Docker Compose is not available"
        echo ""
        echo "Please install Docker Compose:"
        echo "  https://docs.docker.com/compose/install/"
        exit 1
    fi
    print_step "Docker Compose is available"
}

prompt_for_config() {
    echo ""
    echo "════════════════════════════════════════════════════════════"
    echo "  Configuration"
    echo "════════════════════════════════════════════════════════════"
    echo ""
    
    # API Key
    echo -e "${CYAN}Step 1: Get your API key from Automaton Studio${NC}"
    echo "  1. Open Studio in browser (e.g., https://localhost:7091)"
    echo "  2. Go to Settings → API Keys"
    echo "  3. Click 'Create API Key' with scope 'Runner'"
    echo "  4. Copy the API key (starts with ak_runner_...)"
    echo ""
    
    while true; do
        read -p "Enter your API key: " api_key
        if [[ $api_key =~ ^ak_runner_.+ ]]; then
            break
        elif [[ $api_key =~ ^ak_.+ ]]; then
            print_warning "API key should start with 'ak_runner_' for runner scope"
            read -p "Continue anyway? (y/n): " confirm
            if [[ $confirm =~ ^[Yy]$ ]]; then
                break
            fi
        else
            print_error "Invalid API key format. Should start with 'ak_'"
        fi
    done
    
    echo ""
    
    # Server URL
    echo -e "${CYAN}Step 2: Enter your Studio server URL${NC}"
    echo "  Examples:"
    echo "    • https://localhost:7091 (local Studio)"
    echo "    • https://host.docker.internal:7091 (local Studio from Docker)"
    echo "    • https://studio.yourdomain.com (remote Studio)"
    echo ""
    read -p "Server URL [$DEFAULT_SERVER_URL]: " server_url
    server_url=${server_url:-$DEFAULT_SERVER_URL}
    
    # If localhost is used, suggest host.docker.internal
    if [[ $server_url == *"localhost"* ]] || [[ $server_url == *"127.0.0.1"* ]]; then
        echo ""
        print_warning "You entered 'localhost' - Docker containers can't reach localhost!"
        echo ""
        echo "  Suggested alternatives:"
        echo "    • Use 'host.docker.internal' instead of 'localhost' (Mac/Windows)"
        echo "    • Use your machine's IP address (all platforms)"
        echo ""
        suggested_url=$(echo "$server_url" | sed 's/localhost/host.docker.internal/g' | sed 's/127.0.0.1/host.docker.internal/g')
        read -p "Use $suggested_url instead? (y/n): " use_suggestion
        if [[ $use_suggestion =~ ^[Yy]$ ]]; then
            server_url=$suggested_url
        else
            echo ""
            print_info "You can change this later in the .env file"
        fi
    fi
    
    echo ""
    
    # Runner Name
    echo -e "${CYAN}Step 3: Choose a runner name${NC}"
    read -p "Runner name [$DEFAULT_RUNNER_NAME]: " runner_name
    runner_name=${runner_name:-$DEFAULT_RUNNER_NAME}
    
    echo ""
}

create_env_file() {
    print_info "Creating .env configuration file..."
    
    cat > .env << EOF
# Automaton Runner - Local Testing Configuration
# Generated by setup-local-test.sh on $(date)

# REQUIRED: API Key from Automaton Studio
AUTOMATON_API_KEY=$api_key

# REQUIRED: Automaton Studio server URL
AUTOMATON_SERVER_URL=$server_url

# OPTIONAL: Custom runner name
AUTOMATON_RUNNER_NAME=$runner_name

# Data directories (will be created automatically)
DATA_DIR=./data
LOGS_DIR=./logs
CONFIG_DIR=./config
EOF
    
    print_step "Configuration file created: .env"
}

create_directories() {
    print_info "Creating data directories..."
    mkdir -p data logs config
    print_step "Directories created: data/, logs/, config/"
}

build_image() {
    echo ""
    echo "════════════════════════════════════════════════════════════"
    echo "  Building Docker Image"
    echo "════════════════════════════════════════════════════════════"
    echo ""
    print_info "This will take 5-10 minutes on first build..."
    print_info "Building from: $(pwd)"
    echo ""
    
    cd ..
    if docker build -f Automaton.Runner/Dockerfile.production -t automaton-runner:local .; then
        print_step "Docker image built successfully"
    else
        print_error "Failed to build Docker image"
        exit 1
    fi
    cd Automaton.Runner
    
    # Update docker-compose to use local image
    if grep -q "image: automaton-runner:latest" docker-compose.production.yml; then
        sed -i.bak 's/image: automaton-runner:latest/image: automaton-runner:local/g' docker-compose.production.yml
        rm -f docker-compose.production.yml.bak
    fi
}

start_container() {
    echo ""
    echo "════════════════════════════════════════════════════════════"
    echo "  Starting Container"
    echo "════════════════════════════════════════════════════════════"
    echo ""
    
    # Check if compose or docker-compose
    if docker compose version &> /dev/null; then
        COMPOSE_CMD="docker compose"
    else
        COMPOSE_CMD="docker-compose"
    fi
    
    print_info "Starting runner container..."
    if $COMPOSE_CMD -f docker-compose.production.yml up -d; then
        print_step "Container started successfully"
    else
        print_error "Failed to start container"
        exit 1
    fi
    
    echo ""
    print_info "Waiting for runner to initialize (10 seconds)..."
    sleep 10
}

show_logs() {
    echo ""
    echo "════════════════════════════════════════════════════════════"
    echo "  Container Logs (last 30 lines)"
    echo "════════════════════════════════════════════════════════════"
    echo ""
    
    # Check if compose or docker-compose
    if docker compose version &> /dev/null; then
        COMPOSE_CMD="docker compose"
    else
        COMPOSE_CMD="docker-compose"
    fi
    
    $COMPOSE_CMD -f docker-compose.production.yml logs --tail=30
}

show_success() {
    echo ""
    echo -e "${GREEN}"
    echo "════════════════════════════════════════════════════════════"
    echo "  ✓ Setup Complete!"
    echo "════════════════════════════════════════════════════════════"
    echo -e "${NC}"
    echo ""
    echo "Your Automaton Runner is now running!"
    echo ""
    echo "Next steps:"
    echo "  1. Open Automaton Studio: $server_url"
    echo "  2. Go to 'Runners' page"
    echo "  3. You should see '$runner_name' listed and connected"
    echo "  4. Create a test workflow and assign it to your runner"
    echo ""
    echo "Useful commands:"
    echo "  • View logs:    docker-compose -f docker-compose.production.yml logs -f"
    echo "  • Stop runner:  docker-compose -f docker-compose.production.yml down"
    echo "  • Restart:      docker-compose -f docker-compose.production.yml restart"
    echo "  • Status:       docker-compose -f docker-compose.production.yml ps"
    echo ""
    echo "For more information, see LOCAL-TESTING.md"
    echo ""
}

# Main script
main() {
    print_header
    
    # Check prerequisites
    check_docker
    check_compose
    
    # Check if .env already exists
    if [ -f .env ]; then
        echo ""
        print_warning "Configuration file (.env) already exists"
        read -p "Do you want to overwrite it? (y/n): " overwrite
        if [[ ! $overwrite =~ ^[Yy]$ ]]; then
            print_info "Using existing .env file"
            echo ""
            read -p "Do you want to rebuild and restart? (y/n): " rebuild
            if [[ $rebuild =~ ^[Yy]$ ]]; then
                create_directories
                build_image
                start_container
                show_logs
                show_success
            fi
            exit 0
        fi
    fi
    
    # Prompt for configuration
    prompt_for_config
    
    # Create configuration
    create_env_file
    create_directories
    
    # Build and start
    build_image
    start_container
    show_logs
    show_success
}

# Run main function
main
