#!/usr/bin/env node
// Writes the command list in src/automaton-vue/docs/automaton-cli.md from the CLI's own `--help`, between the
// <!-- cli-commands:start --> and <!-- cli-commands:end --> markers. The rest of the page is hand-written.
//   node scripts/generate-cli-reference.mjs            rewrite the block
//   node scripts/generate-cli-reference.mjs --check    fail when the block is out of date (CI)
// Set AUTOMATON_CLI to an installed `automaton` to skip `dotnet run`.
import fs from 'node:fs'
import path from 'node:path'
import { execFileSync } from 'node:child_process'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const page = path.join(root, 'src/automaton-vue/docs/automaton-cli.md')
const start = '<!-- cli-commands:start (generated by scripts/generate-cli-reference.mjs; do not edit) -->'
const end = '<!-- cli-commands:end -->'

const help = process.env.AUTOMATON_CLI
  ? execFileSync(process.env.AUTOMATON_CLI, ['--help'], { encoding: 'utf8' })
  : execFileSync('dotnet', ['run', '--no-launch-profile', '--project', path.join(root, 'src/Automaton.Cli'), '--', '--help'], { encoding: 'utf8' })

const lines = help.replace(/\r\n/g, '\n').split('\n')
const from = lines.findIndex(l => l.trim() === 'Commands:')
if (from < 0) { console.error('No "Commands:" section in the CLI help.'); process.exit(1) }
const rows = []
for (const line of lines.slice(from + 1)) {
  if (!line.trim()) break
  const m = /^\s{2}(\S+(?: <[^>]+>)?)\s{2,}(.*?)\s*(?:\[\])?$/.exec(line)
  if (!m) { console.error(`Cannot parse help line: ${line}`); process.exit(1) }
  rows.push(`| \`automaton ${m[1]}\` | ${m[2].replace(/[\\|]/g, '\\$&')} |`)
}
if (rows.length === 0) { console.error('No commands found in the CLI help.'); process.exit(1) }

const block = [start, '', '| Command | What it does |', '| --- | --- |', ...rows, '', end].join('\n')
const text = fs.readFileSync(page, 'utf8')
const a = text.indexOf('<!-- cli-commands:start')
const b = text.indexOf(end)
if (a < 0 || b < a) { console.error(`${page} has no cli-commands markers.`); process.exit(1) }
const next = text.slice(0, a) + block + text.slice(b + end.length)
if (process.argv.includes('--check')) {
  if (next !== text) { console.error('The command list in automaton-cli.md is out of date. Run: node scripts/generate-cli-reference.mjs'); process.exit(1) }
  console.log('CLI command list is up to date.')
} else {
  fs.writeFileSync(page, next)
  console.log(`Wrote ${rows.length} commands.`)
}
