$ErrorActionPreference = "Stop"

Write-Host "Running Developer..."

$model = "gpt-5.4"
$jsonl = "AgentRuns\current\developer.jsonl"
$metrics = "AgentRuns\current\developer-metrics.json"
$resultPath = "AgentRuns\current\result.md"

Write-Host "Model: $model"

if (-not (Test-Path "AgentRuns\current\task.md")) {
    throw "AgentRuns\current\task.md does not exist."
}

$taskContent = Get-Content "AgentRuns\current\task.md" -Raw

if ([string]::IsNullOrWhiteSpace($taskContent)) {
    throw "AgentRuns\current\task.md is empty."
}

$prompt = @"
Read .agent/agents/developer.md.
Read AgentRuns/current/task.md.
Read AgentRuns/current/context.md if it exists.
Read AgentRuns/current/review.md if it exists.

Follow the developer role instructions.

Important:
- Always write AgentRuns/current/result.md before finishing.
- If verification fails, do not stop silently.
- Capture the failure in result.md.
- Explain whether the failure appears related to the current diff.
- If code changes were made, result.md must still be written.

Use PowerShell Set-Content when writing AgentRuns files.
"@

$codexFailed = $false
$codexError = $null
$codexExitCode = 0

try {
    $prompt | codex exec `
        -m $model `
        --json `
        --dangerously-bypass-approvals-and-sandbox `
        --cd . `
        - `
        2>&1 | Tee-Object $jsonl

    $codexExitCode = $LASTEXITCODE
}
catch {
    $codexFailed = $true
    $codexError = $_
    $codexExitCode = 1
}

$jsonlContent = ""

if (Test-Path $jsonl) {
    $jsonlContent = Get-Content $jsonl -Raw
}

$codexReportedFailure =
    $codexFailed `
    -or $codexExitCode -ne 0 `
    -or $jsonlContent -match '"type":"error"' `
    -or $jsonlContent -match '"type":"turn.failed"'

$resultContent = ""

if (Test-Path $resultPath) {
    $resultContent = Get-Content $resultPath -Raw
}

$gitStatus = git status --short

if ($codexReportedFailure) {
    if ($gitStatus) {
        Write-Host ""
        Write-Host "Developer Codex run failed, but code changes exist."
        Write-Host "Writing recovery result.md so the reviewer can inspect the diff."

        $errorText = ""

        if ($codexError) {
            $errorText = $codexError.ToString()
        }

        $jsonlFailureLines = ""

        if (Test-Path $jsonl) {
            $failureLines = Select-String `
                -Path $jsonl `
                -Pattern '"type":"error"', '"type":"turn.failed"', 'ERROR codex_core', 'Exit code' `
                -ErrorAction SilentlyContinue |
                Select-Object -First 10 |
                ForEach-Object {
                    $line = $_.Line

                    if ($line.Length -gt 1200) {
                        $line.Substring(0, 1200) + "... [truncated]"
                    }
                    else {
                        $line
                    }
                }

            $jsonlFailureLines = $failureLines -join [Environment]::NewLine
        }

        $recovery = @"
## Summary
The developer agent modified files, but the Codex run exited with an error before completing normally.

A recovery result was generated so the reviewer can inspect the current diff.

## Reviewer feedback addressed
- Not available because the developer run did not complete normally.

## Files changed
See git status and git diff.

Current git status:

````text
$gitStatus
````

## Verification
- Codex exited with code $codexExitCode.
- Check AgentRuns/current/developer.jsonl for details.
- Run verification manually if needed.

## Notes
This is a recovery result generated by run-developer.ps1.

Codex error:

````text
$errorText
````

Relevant JSONL failure lines:

````text
$jsonlFailureLines
````
"@

        Set-Content $resultPath $recovery
    }
    else {
        throw "Codex developer failed and no code changes were detected. See $jsonl"
    }
}

# Try to write metrics, but do not fail the whole developer step only because metrics are missing.
try {
    .\.agent\harness\write-agent-metrics.ps1 `
        -Role "developer" `
        -Model $model `
        -JsonlPath $jsonl `
        -MetricsPath $metrics
}
catch {
    Write-Host ""
    Write-Host "Warning: failed to write developer metrics."
    Write-Host $_
}

if (-not (Test-Path $resultPath)) {
    throw "Developer did not create AgentRuns\current\result.md"
}

$resultContent = Get-Content $resultPath -Raw

if ([string]::IsNullOrWhiteSpace($resultContent)) {
    if ($gitStatus) {
        Write-Host ""
        Write-Host "Developer result.md is empty, but code changes exist."
        Write-Host "Writing fallback recovery result.md."

        $fallback = @"
## Summary
The developer step produced code changes but did not write a valid result.md.

A fallback recovery result was generated so the reviewer can inspect the current diff.

## Reviewer feedback addressed
- Unknown.

## Files changed
See git status and git diff.

Current git status:

````text
$gitStatus
````

## Verification
- Developer result was missing or empty.
- Run verification manually if needed.

## Notes
This is a fallback recovery result generated by run-developer.ps1.
"@

        Set-Content $resultPath $fallback
        $resultContent = Get-Content $resultPath -Raw
    }
    else {
        throw "Developer created an empty result.md and no code changes were detected."
    }
}

Write-Host ""
Write-Host "Developer result:"
Write-Host "----------------------------------------"
Get-Content $resultPath

Write-Host ""
Write-Host "Git status:"
Write-Host "----------------------------------------"
git status --short

Write-Host ""
Write-Host "Metrics:"
Write-Host "----------------------------------------"

if (Test-Path $metrics) {
    Get-Content $metrics
}
else {
    Write-Host "No developer metrics file created."
}

if ($codexReportedFailure) {
    Write-Host ""
    Write-Host "Developer completed with recovery result because Codex reported a failure."
    Write-Host "The loop can continue to reviewer."
}
