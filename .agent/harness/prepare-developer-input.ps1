$ErrorActionPreference = "Stop"

Write-Host "Preparing developer input..."

$developerInputPath = "AgentRuns\current\developer-input.md"
$maxTaskChars = 20000
$maxContextChars = 30000
$maxReviewChars = 20000

function Read-TextFileOrEmpty {
    param(
        [string]$Path,
        [int]$MaxChars = 20000
    )

    if (-not (Test-Path $Path)) {
        return ""
    }

    $content = Get-Content $Path -Raw

    if ($content.Length -gt $MaxChars) {
        return $content.Substring(0, $MaxChars) + "`n`n[truncated by prepare-developer-input.ps1]"
    }

    return $content
}

$task = Read-TextFileOrEmpty -Path "AgentRuns\current\task.md" -MaxChars $maxTaskChars
$context = Read-TextFileOrEmpty -Path "AgentRuns\current\context.md" -MaxChars $maxContextChars
$review = Read-TextFileOrEmpty -Path "AgentRuns\current\review.md" -MaxChars $maxReviewChars

$content = @"
# Developer Input

This file is generated by `.agent/harness/prepare-developer-input.ps1`.
Use this prepared input as the source of truth before inspecting repository files.
Prefer exact files listed in the context and avoid broad repository exploration.

## Task

$task

## Context

$context

## Reviewer Feedback

$review
"@

Set-Content $developerInputPath $content

Write-Host "Prepared developer input:"
Write-Host $developerInputPath
