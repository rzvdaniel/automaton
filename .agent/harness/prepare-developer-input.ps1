$ErrorActionPreference = "Stop"

Write-Host "Preparing developer input..."

$developerInputPath = "AgentRuns\current\developer-input.md"
$maxTaskChars = 20000
$maxContextChars = 30000
$maxReviewChars = 20000

function Read-TextFileOrEmpty {
    param(
        [string]$Path,
        [int]$MaxChars = 20000
    )

    if (-not (Test-Path $Path)) {
        return ""
    }

    $content = Get-Content $Path -Raw

    if ($content.Length -gt $MaxChars) {
        return $content.Substring(0, $MaxChars) + "`n`n[truncated by prepare-developer-input.ps1]"
    }

    return $content
}

$scope = $null
$scopeJson = ""
$mode = "unknown"
$developerInputMax = 120000
$maxFilesToInspect = 8

if (Test-Path "AgentRuns\current\scope.json") {
    $scopeJson = Read-TextFileOrEmpty -Path "AgentRuns\current\scope.json" -MaxChars 12000

    if (-not [string]::IsNullOrWhiteSpace($scopeJson)) {
        try {
            $scope = $scopeJson | ConvertFrom-Json
            $mode = $scope.mode

            if ($null -ne $scope.token_budget) {
                if ($null -ne $scope.token_budget.developer_input_max) {
                    $developerInputMax = [int]$scope.token_budget.developer_input_max
                }

                if ($null -ne $scope.token_budget.max_files_to_inspect) {
                    $maxFilesToInspect = [int]$scope.token_budget.max_files_to_inspect
                }
            }
        }
        catch {
            Write-Host "Warning: could not parse scope.json while preparing developer input."
        }
    }
}

if ($mode -eq "micro") {
    $maxTaskChars = 12000
    $maxContextChars = 0
    $maxReviewChars = 0
}
elseif ($mode -eq "tiny") {
    $maxTaskChars = 16000
    $maxContextChars = 8000
    $maxReviewChars = 8000
}
elseif ($mode -eq "small") {
    $maxTaskChars = 20000
    $maxContextChars = 15000
    $maxReviewChars = 12000
}

$task = Read-TextFileOrEmpty -Path "AgentRuns\current\task.md" -MaxChars $maxTaskChars
$context = ""
$review = ""

if ($maxContextChars -gt 0) {
    $context = Read-TextFileOrEmpty -Path "AgentRuns\current\context.md" -MaxChars $maxContextChars
}

if ($maxReviewChars -gt 0) {
    $review = Read-TextFileOrEmpty -Path "AgentRuns\current\review.md" -MaxChars $maxReviewChars
}

$budgetGuidance = @"
## Mode and Budget

Mode: $mode
Developer input target: <= $developerInputMax tokens
Maximum files to inspect before implementing: $maxFilesToInspect

Mandatory exploration rules:
- Read this prepared input first.
- Search before opening files when exact files are unknown.
- Prefer path-limited searches from the task domain instead of repository-wide exploration.
- Stop exploration once the target file or files are found.
- Do not read repository maps, skills, or broad architecture docs for micro tasks unless search fails or the task cannot be understood.
- For micro tasks, inspect no more than 3 files unless unavoidable; explain any extra files in result.md.
"@

$content = @"
# Developer Input

This file is generated by `.agent/harness/prepare-developer-input.ps1`.
Use this prepared input as the source of truth before inspecting repository files.
Prefer exact files listed in the context and avoid broad repository exploration.

$budgetGuidance

## Scope

````json
$scopeJson
````

## Task

$task

## Context

$context

## Reviewer Feedback

$review
"@

Set-Content $developerInputPath $content

Write-Host "Prepared developer input:"
Write-Host $developerInputPath
