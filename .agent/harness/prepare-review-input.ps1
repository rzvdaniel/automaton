$ErrorActionPreference = "Stop"

Write-Host "Preparing reviewer input..."

$reviewInputPath = "AgentRuns\current\review-input.md"
$maxSectionChars = 20000
$maxDiffChars = 60000

function Read-TextFileOrEmpty {
    param(
        [string]$Path,
        [int]$MaxChars = 20000
    )

    if (-not (Test-Path $Path)) {
        return ""
    }

    $content = Get-Content $Path -Raw

    if ($content.Length -gt $MaxChars) {
        return $content.Substring(0, $MaxChars) + "`n`n[truncated by prepare-review-input.ps1]"
    }

    return $content
}

$task = Read-TextFileOrEmpty -Path "AgentRuns\current\task.md" -MaxChars $maxSectionChars
$context = Read-TextFileOrEmpty -Path "AgentRuns\current\context.md" -MaxChars $maxSectionChars
$result = Read-TextFileOrEmpty -Path "AgentRuns\current\result.md" -MaxChars $maxSectionChars
$developerError = Read-TextFileOrEmpty -Path "AgentRuns\current\developer-error-summary.txt" -MaxChars 12000

$changedFiles = git diff --name-only | Out-String
$diffStat = git diff --stat | Out-String
$diff = git diff --unified=3 | Out-String

if ($diff.Length -gt $maxDiffChars) {
    $diff = $diff.Substring(0, $maxDiffChars) + "`n`n[diff truncated by prepare-review-input.ps1]"
}

$content = @"
# Review Input

This file is generated by `.agent/harness/prepare-review-input.ps1`.
Review this prepared input first and avoid reading unrelated repository files unless the diff is insufficient.

## Task

$task

## Context

$context

## Developer Result

$result

## Developer Error Summary

$developerError

## Changed Files

````text
$changedFiles
````

## Diff Stat

````text
$diffStat
````

## Diff

````diff
$diff
````
"@

Set-Content $reviewInputPath $content

Write-Host "Prepared review input:"
Write-Host $reviewInputPath
